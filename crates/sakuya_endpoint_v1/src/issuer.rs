//! How a connection of an endpoint issues its connection IDs after the
//! first: [`EndpointConnectionIdIssuer`].

use alloc::sync::Arc;
use core::fmt;

use sakuya_connection::connection_id::local::{ConnectionIdIssuer, IssuedConnectionId};
use sakuya_datagram_routing_v1::route::{
    association::MatchAssociation, recognizer::ConnectionIdGenerator,
};
use sakuya_wire_v1::connection_id::NonEmptyCid;

use crate::{
    choices::{EndpointChoices, ReceivePosterOf, RegistrationOf},
    domain::Domain,
};

/// Issues the connection IDs of one connection of an endpoint of the
/// choices `E`: generated by the connection's own generator, which made its
/// first one too, and registered with the endpoint's routing for the
/// connection's datagram receiver before they are disclosed.
pub struct EndpointConnectionIdIssuer<E: EndpointChoices> {
    domain: Arc<Domain<E>>,
    generator: E::ConnectionIds,
    poster: ReceivePosterOf<E>,
}

impl<E: EndpointChoices> EndpointConnectionIdIssuer<E> {
    /// The issuer of a connection whose generator is `generator` and whose
    /// datagram receiver `poster` posts to.
    pub(crate) fn new(
        domain: Arc<Domain<E>>,
        generator: E::ConnectionIds,
        poster: ReceivePosterOf<E>,
    ) -> Self {
        Self {
            domain,
            generator,
            poster,
        }
    }
}

impl<E: EndpointChoices> fmt::Debug for EndpointConnectionIdIssuer<E> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("EndpointConnectionIdIssuer")
            .finish_non_exhaustive()
    }
}

/// A connection with a zero-length local connection ID issues none, so the
/// generator of one that issues gives connection IDs that are not empty.
impl<E: EndpointChoices> ConnectionIdIssuer for EndpointConnectionIdIssuer<E> {
    type Registration = RegistrationOf<E>;

    fn issue(&mut self) -> IssuedConnectionId<RegistrationOf<E>> {
        let (cid, token) = self.generator.generate();
        // invariant: only a connection whose first connection ID was not
        // empty issues, and its generator gives none empty
        let id =
            NonEmptyCid::new(cid).expect("an issuing connection's generator gives non-empty IDs");
        let registration = self
            .domain
            .register_posting(MatchAssociation::LocalCid(id), self.poster.clone());
        IssuedConnectionId {
            id,
            token,
            registration,
        }
    }
}
